"""Generates the launcher icons of Yoo: a "Y" on a solid or gradient
background, in the six variants offered in Settings > Personalization >
App icon.

Android: an adaptive icon per variant (vector background and foreground,
shared monochrome layer for themed icons) plus legacy PNGs for Android 7.
"classic" keeps the default names (ic_launcher); the others are
ic_launcher_<id>, used by the activities declared in AndroidManifest.xml.
iOS: the "classic" variant as the app icon (alternate icons need a Mac).

The colors must match AppIconOption.all in lib/core/widgets/yoo_icon.dart,
and the "Y" is the polygon of res/drawable/ic_stat_yoo.xml (24x24 viewport).

Usage (needs Pillow):  python tool/generate_icons.py
"""

import json
import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"

# id: (background, foreground, gradient end or None)
ICONS = {
    "classic": ("1E1D1B", "FAF8F4", None),
    "light": ("FAF8F4", "1E1D1B", None),
    "dark": ("111112", "7DA7E0", None),
    "ocean": ("0090FF", "FFFFFF", "12A594"),
    "forest": ("4F7A4A", "FFFFFF", "1E2A1E"),
    "sunset": ("F76B15", "FFFFFF", "D6409F"),
}

# "Y" in a 24x24 viewport, glyph box x 4..20, y 3..21 (center 12, 12).
GLYPH = [(4, 3), (8.6, 3), (12, 8.9), (15.4, 3), (20, 3), (14, 12.9), (14, 21), (10, 21), (10, 12.9)]
GLYPH_PATH = "M4,3 L8.6,3 L12,8.9 L15.4,3 L20,3 L14,12.9 L14,21 L10,21 L10,12.9 Z"
# Share of the visible icon taken by the glyph's height: 40 of the 72 dp an
# adaptive icon shows. Also used by YooIcon in the app.
GLYPH_SHARE = 40 / 72
SUPERSAMPLE = 4
LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def name_of(icon_id: str) -> str:
    return "ic_launcher" if icon_id == "classic" else f"ic_launcher_{icon_id}"


def rgb(hex_color: str) -> tuple[int, int, int]:
    return tuple(int(hex_color[i : i + 2], 16) for i in (0, 2, 4))


def write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


# ---------------------------------------------------------------------------
# Android adaptive icons
# ---------------------------------------------------------------------------

VECTOR_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py: edit the script, not this file. -->
"""


def background_xml(background: str, gradient_end: str | None) -> str:
    if gradient_end is None:
        fill = f'android:fillColor="#FF{background}"'
        return (
            VECTOR_HEADER
            + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        {fill}
        android:pathData="M0,0h108v108h-108z" />
</vector>
"""
        )
    # Diagonal gradient across the visible 72 dp, like the in-app preview.
    return (
        VECTOR_HEADER
        + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="18"
                android:startY="18"
                android:endX="90"
                android:endY="90">
                <item android:offset="0" android:color="#FF{background}" />
                <item android:offset="1" android:color="#FF{gradient_end}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""
    )


def glyph_xml(color: str) -> str:
    # The glyph is 18 units tall: scale it to 40 dp, centered on (54, 54).
    scale = 40 / 18
    offset = 54 - 12 * scale
    return (
        VECTOR_HEADER
        + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{scale:.4f}"
        android:scaleY="{scale:.4f}"
        android:translateX="{offset:.3f}"
        android:translateY="{offset:.3f}">
        <path
            android:fillColor="#FF{color}"
            android:pathData="{GLYPH_PATH}" />
    </group>
</vector>
"""
    )


def adaptive_xml(name: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py: edit the script, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/{name}_background" />
    <foreground android:drawable="@drawable/{name}_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


# ---------------------------------------------------------------------------
# Bitmaps (legacy Android icons, iOS)
# ---------------------------------------------------------------------------


def fill_image(size: int, background: str, gradient_end: str | None) -> Image.Image:
    """The background, solid or with a top-left to bottom-right gradient."""
    if gradient_end is None:
        return Image.new("RGB", (size, size), rgb(background))
    start, end = rgb(background), rgb(gradient_end)
    span = max(2 * (size - 1), 1)
    pixels = []
    for y in range(size):
        for x in range(size):
            t = (x + y) / span
            pixels.append(tuple(round(s + (e - s) * t) for s, e in zip(start, end)))
    image = Image.new("RGB", (size, size))
    image.putdata(pixels)
    return image


def draw_icon(size: int, colors: tuple, rounded: bool) -> Image.Image:
    """A [size] px icon. Rounded corners for Android legacy icons, full bleed
    for iOS (which applies its own mask)."""
    background, foreground, gradient_end = colors
    big = size * SUPERSAMPLE
    image = fill_image(big, background, gradient_end).convert("RGBA")
    draw = ImageDraw.Draw(image)
    scale = big * GLYPH_SHARE / 18  # the glyph is 18 units tall
    points = [(big / 2 + (x - 12) * scale, big / 2 + (y - 12) * scale) for x, y in GLYPH]
    draw.polygon(points, fill=rgb(foreground))
    if rounded:
        mask = Image.new("L", (big, big), 0)
        ImageDraw.Draw(mask).rounded_rectangle([0, 0, big - 1, big - 1], radius=big * 0.22, fill=255)
        image.putalpha(mask)
    else:
        image = image.convert("RGB")
    return image.resize((size, size), Image.LANCZOS)


def android() -> None:
    write(RES / "drawable/ic_launcher_monochrome.xml", glyph_xml("FFFFFF"))
    for icon_id, colors in ICONS.items():
        background, foreground, gradient_end = colors
        name = name_of(icon_id)
        write(RES / f"drawable/{name}_background.xml", background_xml(background, gradient_end))
        write(RES / f"drawable/{name}_foreground.xml", glyph_xml(foreground))
        write(RES / f"mipmap-anydpi-v26/{name}.xml", adaptive_xml(name))
        for folder, size in LEGACY_SIZES.items():
            path = RES / f"mipmap-{folder}/{name}.png"
            path.parent.mkdir(parents=True, exist_ok=True)
            draw_icon(size, colors, rounded=True).save(path)


def ios() -> None:
    folder = ROOT / "ios/Runner/Assets.xcassets/AppIcon.appiconset"
    contents = json.loads((folder / "Contents.json").read_text(encoding="utf-8"))
    for entry in contents["images"]:
        points = float(entry["size"].split("x")[0])
        pixels = round(points * int(entry["scale"].rstrip("x")))
        draw_icon(pixels, ICONS["classic"], rounded=False).save(folder / entry["filename"])


if __name__ == "__main__":
    android()
    ios()
    print("Icons written.")
